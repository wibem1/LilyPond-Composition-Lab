// Roll marked chords in the MIDI-only score after articulation has set note lengths.
export const arpeggioPrelude=String.raw`
#(define (lab:duration-number dur)
  (if (defined? 'ly:duration->number) (ly:duration->number dur)
    (ly:moment-main (ly:duration-length dur))))
#(define (lab:arpeggio-playback music)
  (let ((chords '()) (connections '()) (offsets '()) (tempos '()) (directions '()))
    ;; State: persistent direction/style, one-shot direction/style, tempo.
    (define (walk m state time group scope)
      (let* ((name (ly:music-property m 'name))
             (elements (ly:music-property m 'elements))
             (element (ly:music-property m 'element))
             (context (ly:music-property m 'context-type #f))
             (target (if (and (eq? name 'ContextSpeccedMusic)
                              (not (ly:music-property m 'create-new #f))) context scope))
             (new-group (if (and (eq? name 'ContextSpeccedMusic)
                                 (ly:music-property m 'create-new #f)
                                 (or (memq context '(PianoStaff GrandStaff StaffGroup))
                                     (not group))) m group)))
        (if (eq? name 'ContextSpeccedMusic)
          (for-each (lambda (op)
            (if (and (pair? op) (eq? (car op) 'assign)
                     (eq? (cadr op) 'connectArpeggios))
              (set! connections (cons (list new-group time (caddr op) #f) connections))))
            (ly:music-property m 'property-operations)))
        (cond
          ((and (memq name '(OverrideProperty RevertProperty))
                (eq? (ly:music-property m 'symbol) 'Arpeggio))
           (let* ((path (ly:music-property m 'grob-property-path))
                  (prop (and (pair? path) (car path)))
                  (once (ly:music-property m 'once #f))
                  (value (ly:music-property m 'grob-value)))
             (cond
               ((eq? prop 'arpeggio-direction)
                (if (memq target '(PianoStaff GrandStaff StaffGroup))
                  (set! directions (cons (list new-group time
                    (if (eq? name 'RevertProperty) 1 (if (equal? value -1) -1 1)) once) directions)))
                (vector-set! state (if once 2 0)
                  (if (eq? name 'RevertProperty) 1 (if (equal? value -1) -1 1))))
               ((eq? prop 'stencil)
                (vector-set! state (if once 3 1)
                  (or (eq? name 'RevertProperty)
                      (not (eq? value ly:chord-bracket::print))))))))
          ((eq? name 'PropertySet)
           (case (ly:music-property m 'symbol)
             ((tempoWholesPerMinute)
              (let ((v (ly:music-property m 'value)))
                (let ((tempo (if (ly:moment? v) (ly:moment-main v) v)))
                  (vector-set! state 4 tempo)
                  (set! tempos (cons (cons time tempo) tempos)))))
             ((connectArpeggios)
              (set! connections (cons (list new-group time (ly:music-property m 'value) (ly:music-property m 'once #f)) connections)))))
          ((eq? name 'EventChord)
           (if (pair? (vector-ref state 5))
             (for-each (lambda (n) (set! offsets (cons (cons n 0) offsets))) (lab:notes m)))
           (vector-set! state 5
             (if (and (pair? (lab:notes m))
                      (or (pair? (vector-ref state 5))
                          (any (lambda (e) (eq? (ly:music-property e 'name) 'ArpeggioEvent)) elements))
                      (any (lambda (e) (eq? (ly:music-property e 'name) 'TieEvent)) elements))
               (lab:notes m) '()))
           (if (any (lambda (e) (eq? (ly:music-property e 'name) 'ArpeggioEvent)) elements)
             (begin
               (if (if (eq? (vector-ref state 3) 'unset) (vector-ref state 1) (vector-ref state 3))
                 (set! chords (cons (vector m time new-group
                   (if (eq? (vector-ref state 2) 'unset) (vector-ref state 0) (vector-ref state 2))
                   (vector-ref state 4)) chords)))
               (vector-set! state 2 'unset) (vector-set! state 3 'unset))))
          ((eq? name 'SequentialMusic)
           (let ((at time))
             (for-each (lambda (e)
               (walk e state at new-group target)
               (set! at (+ at (ly:moment-main (ly:music-length e))))) elements)))
          ((eq? name 'SimultaneousMusic)
           (for-each (lambda (e) (walk e (vector-copy state) time new-group target)) elements))
          ((eq? name 'GraceMusic) #f)
          (else
           (if (ly:music? element) (walk element state time new-group target))
           (for-each (lambda (e) (walk e state time new-group target)) elements)))))
    (define (connected? chord)
      (let ((matches (filter (lambda (c)
                       (and (eq? (car c) (vector-ref chord 2))
                            (if (cadddr c) (= (cadr c) (vector-ref chord 1))
                                (<= (cadr c) (vector-ref chord 1))))) connections)))
        (and (pair? matches)
          (caddr (car (sort matches (lambda (a b) (> (cadr a) (cadr b)))))))))
    (define (tempo-at chord)
      (let ((matches (filter (lambda (t) (<= (car t) (vector-ref chord 1))) tempos)))
        (if (null? matches) (vector-ref chord 4)
          (cdr (car (sort matches (lambda (a b) (> (car a) (car b)))))))))
    (define (direction-at chord)
      (let ((matches (filter (lambda (d)
                       (and (eq? (car d) (vector-ref chord 2))
                         (if (cadddr d) (= (cadr d) (vector-ref chord 1))
                           (<= (cadr d) (vector-ref chord 1))))) directions)))
        (if (or (not (connected? chord)) (null? matches)) (vector-ref chord 3)
          (caddr (car (sort matches (lambda (a b) (> (cadr a) (cadr b)))))))))
    (define (same-roll? a b)
      (and (connected? a) (connected? b)
           (eq? (vector-ref a 2) (vector-ref b 2))
           (= (vector-ref a 1) (vector-ref b 1))
           (= (direction-at a) (direction-at b))))
    (walk music (vector 1 #t 'unset 'unset 15 '()) 0 #f #f)
    (let loop ((todo chords))
      (if (pair? todo)
        (let* ((first (car todo))
               (members (filter (lambda (c) (or (eq? c first) (same-roll? first c))) todo))
               (notes (append-map (lambda (c) (lab:notes (vector-ref c 0))) members))
               (ordered (sort notes (lambda (a b)
                 (< (* (direction-at first) (ly:pitch-semitones (ly:music-property a 'pitch)))
                    (* (direction-at first) (ly:pitch-semitones (ly:music-property b 'pitch))))))))
          (if (> (length ordered) 1)
            (let* ((tempo (tempo-at first))
                   (shortest (apply min (map (lambda (n)
                     (lab:duration-number (ly:music-property n 'duration))) ordered)))
                   ;; App interpretation: 25-55 ms per gap, <= 250 ms total,
                   ;; and <= one quarter of the shortest articulated note.
                   (gap-seconds (min 11/200 (max 1/40 (/ 15 (* 16 tempo)))))
                   (spread (min (/ shortest 4) (* tempo 1/240)
                                (* (/ (* gap-seconds tempo) 60) (- (length ordered) 1))))
                   (gap (/ spread (- (length ordered) 1))))
              (for-each (lambda (n i) (set! offsets (cons (cons n (* i gap)) offsets)))
                        ordered (iota (length ordered)))))
          (loop (filter (lambda (c) (not (memq c members))) todo)))))
    (music-map
      (lambda (m)
        (let* ((notes (lab:notes m))
               (has-offset (and (eq? (ly:music-property m 'name) 'EventChord)
                                (any (lambda (n) (assq n offsets)) notes))))
          (if (not has-offset) m
            (let* ((other (filter (lambda (e)
                         (not (memq (ly:music-property e 'name) '(NoteEvent ArpeggioEvent TieEvent))))
                                 (ly:music-property m 'elements)))
                   (ties (filter (lambda (e) (eq? (ly:music-property e 'name) 'TieEvent))
                                 (ly:music-property m 'elements)))
                   (voices (map (lambda (n)
                     (let* ((offset (cdr (assq n offsets)))
                            (duration (lab:duration-number (ly:music-property n 'duration)))
                            (copy (ly:music-deep-copy n)))
                       (ly:music-set-property! copy 'duration (ly:make-duration 0 0 (- duration offset)))
                       (make-music 'ContextSpeccedMusic 'context-type 'Voice
                         'context-id (format #f "lab-arpeggio-~a" (ly:pitch-semitones (ly:music-property n 'pitch)))
                         'element (make-sequential-music
                         (append
                           (if (> offset 0) (list (make-music 'SkipMusic 'duration (ly:make-duration 0 0 offset))) '())
                           (list (make-music 'EventChord 'elements
                             (append (list copy) (map ly:music-deep-copy ties)
                               (map ly:music-deep-copy (filter (lambda (e)
                                 (memq (ly:music-property e 'name) '(AbsoluteDynamicEvent ArticulationEvent))) other)))))))))) notes)))
              (make-music 'SimultaneousMusic 'elements
                (cons (make-sequential-music (list
                  (make-music 'EventChord 'elements (map ly:music-deep-copy other))
                  (make-music 'SkipMusic 'duration (ly:make-duration 0 0
                    (apply max (map (lambda (n) (lab:duration-number (ly:music-property n 'duration))) notes))))))
                  voices)))))) music)))
labArpeggioPlayback = #(define-music-function (music) (ly:music?)
  (lab:arpeggio-playback music))
`;
